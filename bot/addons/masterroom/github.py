# Multi-account GitHub helpers for Master Room with batched file push via Git Trees API.
# Co-authored with CoCo
"""Multi-account GitHub helpers for Master Room (v0.3).

Lilush itself does not push code — that's the coder-bot's job. Lilush
only needs to:

1. **Create a repository** under the chosen GitHub owner, then hand
   the ``clone_url`` to the coder-bot so it can push generated code.
2. **Poll deploy status** of the latest commit so the project card
   in «📂 Проекты» reflects what Render / Oracle did with the push.

Both calls are parameterised by *account* (multi-GitHub support).
The token itself never lives in ``state.json`` — :func:`_resolve_token`
reads it from the env-var named in ``account["token_ref"]`` at call
time. Tests pass a ``token`` directly so they don't depend on env.

Why direct httpx instead of PyGithub? PyGithub is a 1.5MB sync
dependency; we only need three endpoints. Async + small.
"""

from __future__ import annotations

import asyncio
import logging
import os
from typing import Any, Optional

import httpx

logger = logging.getLogger(__name__)

GITHUB_API = "https://api.github.com"
USER_AGENT = "lilush-masterroom/0.3"
DEFAULT_TIMEOUT = 20.0


class GitHubError(RuntimeError):
    """GitHub API call failed (network, 4xx, 5xx). Same shape as
    :class:`CoderClientError` for symmetric error rendering.
    """

    def __init__(self, message: str, status: int | None = None,
                 payload: Any = None):
        super().__init__(message)
        self.status = status
        self.payload = payload


def _resolve_token(account: dict[str, Any], explicit: str | None = None) -> str:
    """Pull the GitHub token, preferring the explicit arg for tests."""
    if explicit:
        return explicit
    # Token entered directly in the bot and stored in state takes priority.
    stored = str(account.get("token", "") or "").strip()
    if stored:
        return stored
    # Vault: look up an encrypted API key stored under provider "github".
    try:
        from ..vault.handlers import get_working_api_key
        found = get_working_api_key("github")
        if found and found[0]:
            return str(found[0]).strip()
    except Exception:  # noqa: BLE001 — vault optional
        pass
    ref = str(account.get("token_ref", "GITHUB_TOKEN") or "GITHUB_TOKEN")
    return os.environ.get(ref, "")


def _headers(token: str) -> dict[str, str]:
    return {
        "Accept": "application/vnd.github+json",
        "User-Agent": USER_AGENT,
        "X-GitHub-Api-Version": "2022-11-28",
        **({"Authorization": f"Bearer {token}"} if token else {}),
    }


async def _request(
    method: str, url: str, *, token: str,
    json: dict | None = None,
    client: Optional[httpx.AsyncClient] = None,
    timeout: float = DEFAULT_TIMEOUT,
) -> Any:
    own = client is None
    cli = client or httpx.AsyncClient(timeout=timeout)
    try:
        try:
            r = await cli.request(method, url, json=json, headers=_headers(token))
        except httpx.HTTPError as e:
            raise GitHubError(f"{method} {url} failed: {e}") from e
        if r.status_code >= 400:
            try:
                payload = r.json()
            except Exception:  # noqa: BLE001
                payload = {"text": r.text[:200]}
            raise GitHubError(
                f"{method} {url} returned {r.status_code}",
                status=r.status_code,
                payload=payload,
            )
        try:
            return r.json()
        except Exception:  # noqa: BLE001
            return {"raw": r.text[:200]}
    finally:
        if own:
            await cli.aclose()


async def create_repo(
    account: dict[str, Any],
    name: str,
    *,
    visibility: str | None = None,
    description: str = "",
    auto_init: bool = True,
    token: str | None = None,
    client: Optional[httpx.AsyncClient] = None,
) -> dict[str, Any]:
    """Create a new repository under ``account['owner']``.

    Returns the GitHub API repo object so the caller can pull
    ``clone_url``, ``ssh_url``, ``html_url``, etc.
    """
    tok = _resolve_token(account, token)
    if not tok:
        raise GitHubError("github token missing (set env var or pass token=)")
    vis = visibility or account.get("default_visibility", "private")
    if vis not in {"public", "private"}:
        vis = "private"
    body = {
        "name": name,
        "private": vis == "private",
        "description": description or f"Generated by Master Room → {name}",
        "auto_init": auto_init,
    }
    owner = str(account.get("owner", "")).strip()
    if not owner:
        raise GitHubError("github account has no owner set")
    # Personal vs org endpoint: detect via /users/<owner> later if we
    # need fancy handling; for v1 we assume the auth token's
    # default user matches the owner OR the owner is an org. The
    # /orgs/<owner>/repos endpoint requires the token to belong to a
    # member with create rights; if it 404s we fall back to /user/repos.
    org_url = f"{GITHUB_API}/orgs/{owner}/repos"
    try:
        return await _request("POST", org_url, token=tok, json=body, client=client)
    except GitHubError as e:
        if e.status in (403, 404):
            # personal account; create under the authenticated user.
            # Classic PATs get 404 from /orgs/<user>/repos, but
            # fine-grained PATs (github_pat_...) get 403 — fall back
            # to /user/repos in both cases.
            return await _request("POST", f"{GITHUB_API}/user/repos",
                                  token=tok, json=body, client=client)
        raise


async def get_deploy_status(
    account: dict[str, Any],
    repo: str,
    sha: str = "HEAD",
    *,
    token: str | None = None,
    client: Optional[httpx.AsyncClient] = None,
) -> dict[str, Any]:
    """Fetch the combined commit status + check runs for one SHA.

    Returns ``{state, checks: [{name, status, conclusion, html_url}]}``
    summarising what GitHub thinks of the latest deploy.
    """
    tok = _resolve_token(account, token)
    if not tok:
        raise GitHubError("github token missing")
    owner = str(account.get("owner", "")).strip()
    if not owner or not repo:
        raise GitHubError("owner + repo required")
    # Combined status
    status_url = f"{GITHUB_API}/repos/{owner}/{repo}/commits/{sha}/status"
    checks_url = f"{GITHUB_API}/repos/{owner}/{repo}/commits/{sha}/check-runs"
    status = await _request("GET", status_url, token=tok, client=client)
    checks = await _request("GET", checks_url, token=tok, client=client)
    out_checks = []
    for run in (checks.get("check_runs", []) or []) if isinstance(checks, dict) else []:
        out_checks.append({
            "name": run.get("name", ""),
            "status": run.get("status", ""),
            "conclusion": run.get("conclusion", ""),
            "html_url": run.get("html_url", ""),
        })
    return {
        "state": status.get("state", "pending") if isinstance(status, dict) else "pending",
        "checks": out_checks,
    }


async def trigger_workflow(
    account: dict[str, Any],
    repo: str,
    workflow: str,
    ref: str = "main",
    inputs: dict | None = None,
    *,
    token: str | None = None,
    client: Optional[httpx.AsyncClient] = None,
) -> dict[str, Any]:
    """Manually dispatch a GitHub Actions workflow (used for redeploy)."""
    tok = _resolve_token(account, token)
    if not tok:
        raise GitHubError("github token missing")
    owner = str(account.get("owner", "")).strip()
    if not owner or not repo or not workflow:
        raise GitHubError("owner + repo + workflow required")
    url = f"{GITHUB_API}/repos/{owner}/{repo}/actions/workflows/{workflow}/dispatches"
    body = {"ref": ref, "inputs": inputs or {}}
    # workflow dispatch returns 204 No Content on success.
    own = client is None
    cli = client or httpx.AsyncClient(timeout=DEFAULT_TIMEOUT)
    try:
        try:
            r = await cli.post(url, json=body, headers=_headers(tok))
        except httpx.HTTPError as e:
            raise GitHubError(f"POST {url} failed: {e}") from e
        if r.status_code >= 400:
            try:
                payload = r.json()
            except Exception:  # noqa: BLE001
                payload = {"text": r.text[:200]}
            raise GitHubError(f"POST {url} returned {r.status_code}",
                              status=r.status_code, payload=payload)
        return {"ok": True, "status": r.status_code}
    finally:
        if own:
            await cli.aclose()


# ─── Branch management ──────────────────────────────────────────────────────────

async def create_branch(
    account: dict,
    repo: str,
    branch: str,
    *,
    from_branch: str = "main",
    token: str | None = None,
) -> dict:
    """Create a new branch off ``from_branch``.

    Returns the new ref object from GitHub.  If the branch already exists
    the existing ref is returned unchanged (idempotent).
    """
    tok = _resolve_token(account, token)
    if not tok:
        raise GitHubError("github token missing")
    owner = str(account.get("owner", "")).strip()
    if not owner or not repo:
        raise GitHubError("owner + repo required")

    async with httpx.AsyncClient(timeout=DEFAULT_TIMEOUT) as client:
        # Resolve the SHA of the source branch
        source_url = f"{GITHUB_API}/repos/{owner}/{repo}/git/ref/heads/{from_branch}"
        r = await client.get(source_url, headers=_headers(tok))
        if r.status_code >= 400:
            raise GitHubError(
                f"Cannot read source branch '{from_branch}' ({r.status_code})",
                status=r.status_code,
            )
        source_sha = r.json()["object"]["sha"]

        # Create the new ref
        create_url = f"{GITHUB_API}/repos/{owner}/{repo}/git/refs"
        body = {"ref": f"refs/heads/{branch}", "sha": source_sha}
        r2 = await client.post(create_url, json=body, headers=_headers(tok))
        if r2.status_code == 422:
            # Branch already exists — fetch and return it
            existing_url = f"{GITHUB_API}/repos/{owner}/{repo}/git/ref/heads/{branch}"
            r3 = await client.get(existing_url, headers=_headers(tok))
            if r3.status_code < 400:
                return r3.json()
            raise GitHubError(
                f"Branch exists but cannot read it ({r3.status_code})",
                status=r3.status_code,
            )
        if r2.status_code >= 400:
            raise GitHubError(
                f"Branch creation failed ({r2.status_code})",
                status=r2.status_code,
                payload=r2.json() if r2.headers.get("content-type", "").startswith("application/json") else None,
            )
        return r2.json()


async def create_pull_request(
    account: dict,
    repo: str,
    title: str,
    body: str,
    head: str,
    base: str = "main",
    *,
    draft: bool = False,
    token: str | None = None,
) -> dict:
    """Open a pull request from ``head`` branch into ``base``.

    Parameters
    ----------
    account : dict
        GitHub account dict (must have ``owner``, token source).
    repo : str
        Repository name (without owner prefix).
    title : str
        PR title shown on GitHub.
    body : str
        PR description in Markdown.
    head : str
        Source branch name (e.g. ``feature/task-abc123``).
    base : str
        Target branch (default ``main``).
    draft : bool
        Open as a draft PR (default False).
    token : str | None
        Explicit token override for tests.

    Returns
    -------
    dict
        GitHub PR object with ``html_url``, ``number``, ``state``, etc.
    """
    tok = _resolve_token(account, token)
    if not tok:
        raise GitHubError("github token missing")
    owner = str(account.get("owner", "")).strip()
    if not owner or not repo:
        raise GitHubError("owner + repo required")
    if not head or not title:
        raise GitHubError("head branch and title are required")

    url = f"{GITHUB_API}/repos/{owner}/{repo}/pulls"
    pr_body = {
        "title": title,
        "body": body or "",
        "head": head,
        "base": base,
        "draft": draft,
    }
    return await _request("POST", url, token=tok, json=pr_body)


async def get_pull_request(
    account: dict,
    repo: str,
    pr_number: int,
    *,
    token: str | None = None,
) -> dict:
    """Fetch a pull request by number.  Returns the GitHub PR object."""
    tok = _resolve_token(account, token)
    owner = str(account.get("owner", "")).strip()
    url = f"{GITHUB_API}/repos/{owner}/{repo}/pulls/{pr_number}"
    return await _request("GET", url, token=tok)


async def list_pr_review_comments(
    account: dict,
    repo: str,
    pr_number: int,
    *,
    token: str | None = None,
) -> list[dict]:
    """Return all review comments on a PR (paginated, up to 100)."""
    tok = _resolve_token(account, token)
    owner = str(account.get("owner", "")).strip()
    url = f"{GITHUB_API}/repos/{owner}/{repo}/pulls/{pr_number}/comments"
    result = await _request("GET", url, token=tok)
    return result if isinstance(result, list) else []


async def merge_pull_request(
    account: dict,
    repo: str,
    pr_number: int,
    commit_title: str = "",
    merge_method: str = "squash",
    *,
    token: str | None = None,
) -> dict:
    """Merge a pull request (default: squash merge).

    ``merge_method`` can be ``merge``, ``squash``, or ``rebase``.
    Raises :class:`GitHubError` on failure (e.g. CI still pending, conflicts).
    """
    tok = _resolve_token(account, token)
    owner = str(account.get("owner", "")).strip()
    url = f"{GITHUB_API}/repos/{owner}/{repo}/pulls/{pr_number}/merge"
    body: dict = {"merge_method": merge_method}
    if commit_title:
        body["commit_title"] = commit_title
    return await _request("PUT", url, token=tok, json=body)


# ─── Batched file push via Git Trees API ─────────────────────────────────────

BATCH_SIZE = 95  # max files per commit (GitHub soft limit = 100 per tree call)


async def get_authenticated_user(token: str) -> dict:
    """Return the GitHub user object for ``token`` (validates the token).

    Used to auto-detect the ``owner`` login during single-step setup.
    Raises :class:`GitHubError` if the token is invalid.
    """
    if not token:
        raise GitHubError("token is empty")
    async with httpx.AsyncClient(timeout=30.0) as client:
        r = await client.get(f"{GITHUB_API}/user", headers=_headers(token))
        if r.status_code == 401:
            raise GitHubError("токен недействителен (401)", status=401)
        if r.status_code >= 400:
            raise GitHubError(f"user lookup failed ({r.status_code})", status=r.status_code)
        return r.json()


async def get_repo(
    account: dict,
    repo: str,
    *,
    token: str | None = None,
) -> dict:
    """Fetch a repository object (used to read ``default_branch``)."""
    tok = _resolve_token(account, token)
    if not tok:
        raise GitHubError("github token missing")
    owner = str(account.get("owner", "")).strip()
    url = f"{GITHUB_API}/repos/{owner}/{repo}"
    async with httpx.AsyncClient(timeout=30.0) as client:
        r = await client.get(url, headers=_headers(tok))
        if r.status_code >= 400:
            raise GitHubError(f"repo lookup failed ({r.status_code})", status=r.status_code)
        return r.json()


async def list_repos(
    account: dict,
    *,
    token: str | None = None,
    per_page: int = 100,
) -> list[dict]:
    """List repositories the account can access, newest push first.

    Used to resolve the «репозиторий для авто-редактирования» default:
    exactly one repo → that one; two or more → the most recently pushed.
    """
    tok = _resolve_token(account, token)
    if not tok:
        raise GitHubError("github token missing")
    url = f"{GITHUB_API}/user/repos?per_page={per_page}&sort=pushed&direction=desc&affiliation=owner"
    async with httpx.AsyncClient(timeout=30.0) as client:
        r = await client.get(url, headers=_headers(tok))
        if r.status_code >= 400:
            raise GitHubError(f"repo list failed ({r.status_code})", status=r.status_code)
        data = r.json()
        return list(data) if isinstance(data, list) else []


async def _create_blob(
    token: str, owner: str, repo: str, content_bytes: bytes,
    client: httpx.AsyncClient,
) -> str:
    """Create a blob in the repo and return its SHA.

    Retries on 403/429: GitHub's secondary rate limit kicks in after a few
    hundred rapid POSTs, so large multi-batch pushes were dying mid-way
    with «blob creation failed (403)». We honour ``Retry-After`` when
    present and fall back to exponential backoff.
    """
    import base64 as b64
    url = f"{GITHUB_API}/repos/{owner}/{repo}/git/blobs"
    body = {"content": b64.b64encode(content_bytes).decode(), "encoding": "base64"}
    last_status = None
    for attempt in range(5):
        r = await client.post(url, json=body, headers=_headers(token))
        if r.status_code < 400:
            return r.json()["sha"]
        last_status = r.status_code
        if r.status_code in (403, 429) and attempt < 4:
            try:
                retry_after = int(r.headers.get("Retry-After", "0") or "0")
            except ValueError:
                retry_after = 0
            wait = retry_after if retry_after > 0 else min(60, 2 ** (attempt + 2))
            logger.warning(
                "GitHub rate limit on blob creation (%s), retry %d/4 in %ds",
                r.status_code, attempt + 1, wait,
            )
            await asyncio.sleep(wait)
            continue
        detail = ""
        try:
            detail = f": {r.json().get('message', '')}"
        except Exception:  # noqa: BLE001
            pass
        raise GitHubError(
            f"blob creation failed ({r.status_code}){detail}",
            status=r.status_code,
        )
    raise GitHubError(
        f"blob creation failed ({last_status}): rate limit retries exhausted",
        status=last_status,
    )


async def _get_ref_sha(
    token: str, owner: str, repo: str, branch: str,
    client: httpx.AsyncClient,
) -> str:
    """Get the current commit SHA at the tip of ``branch``."""
    url = f"{GITHUB_API}/repos/{owner}/{repo}/git/ref/heads/{branch}"
    r = await client.get(url, headers=_headers(token))
    if r.status_code >= 400:
        raise GitHubError(f"ref lookup failed ({r.status_code})", status=r.status_code)
    return r.json()["object"]["sha"]


async def _create_tree(
    token: str, owner: str, repo: str, base_sha: str,
    tree_items: list[dict], client: httpx.AsyncClient,
) -> str:
    """Create a Git tree with the given items on top of ``base_sha``."""
    url = f"{GITHUB_API}/repos/{owner}/{repo}/git/trees"
    body = {"base_tree": base_sha, "tree": tree_items}
    r = await client.post(url, json=body, headers=_headers(token))
    if r.status_code >= 400:
        raise GitHubError(f"tree creation failed ({r.status_code})", status=r.status_code)
    return r.json()["sha"]


async def _create_commit(
    token: str, owner: str, repo: str,
    tree_sha: str, parent_sha: str, message: str,
    client: httpx.AsyncClient,
) -> str:
    """Create a commit pointing to ``tree_sha`` with parent ``parent_sha``."""
    url = f"{GITHUB_API}/repos/{owner}/{repo}/git/commits"
    body = {"message": message, "tree": tree_sha, "parents": [parent_sha]}
    r = await client.post(url, json=body, headers=_headers(token))
    if r.status_code >= 400:
        raise GitHubError(f"commit creation failed ({r.status_code})", status=r.status_code)
    return r.json()["sha"]


async def _update_ref(
    token: str, owner: str, repo: str, branch: str, sha: str,
    client: httpx.AsyncClient,
) -> None:
    """Fast-forward the branch ref to ``sha``."""
    url = f"{GITHUB_API}/repos/{owner}/{repo}/git/refs/heads/{branch}"
    r = await client.patch(url, json={"sha": sha}, headers=_headers(token))
    if r.status_code >= 400:
        raise GitHubError(f"ref update failed ({r.status_code})", status=r.status_code)


async def push_files_batched(
    account: dict,
    repo: str,
    files: list[tuple[str, bytes]],
    *,
    branch: str = "main",
    batch_size: int = BATCH_SIZE,
    token: str | None = None,
    on_batch_done: Any = None,
) -> dict:
    """Push ``files`` to ``repo`` in batches of ``batch_size``.

    Parameters
    ----------
    account : dict
        GitHub account from state (must have ``owner``, ``token_ref``).
    repo : str
        Repository name (without owner prefix).
    files : list of (path, content_bytes)
        Each entry is (relative path in repo, raw file content).
    branch : str
        Target branch (default ``main``).
    batch_size : int
        Max files per commit (default 95).
    token : str | None
        Explicit token override for tests.
    on_batch_done : callable | None
        Optional async callback ``(batch_num, total_batches, commit_sha)``
        called after each batch commits — useful for progress messages.

    Returns
    -------
    dict with ``{commits: int, total_files: int, head_sha: str}``
    """
    tok = _resolve_token(account, token)
    if not tok:
        raise GitHubError("github token missing")
    owner = str(account.get("owner", "")).strip()
    if not owner or not repo:
        raise GitHubError("owner + repo required")

    total_files = len(files)
    total_batches = (total_files + batch_size - 1) // batch_size
    commits = 0

    async with httpx.AsyncClient(timeout=60.0) as client:
        head_sha = await _get_ref_sha(tok, owner, repo, branch, client)

        for batch_idx in range(total_batches):
            start = batch_idx * batch_size
            batch = files[start:start + batch_size]

            tree_items = []
            for rel_path, content in batch:
                blob_sha = await _create_blob(tok, owner, repo, content, client)
                tree_items.append({
                    "path": rel_path,
                    "mode": "100644",
                    "type": "blob",
                    "sha": blob_sha,
                })
                # Throttle: GitHub recommends ≤ ~1 mutating request/sec;
                # without this the secondary rate limit fires mid-push.
                await asyncio.sleep(0.35)

            tree_sha = await _create_tree(tok, owner, repo, head_sha, tree_items, client)
            msg = f"batch {batch_idx + 1}/{total_batches}: {len(batch)} files"
            head_sha = await _create_commit(tok, owner, repo, tree_sha, head_sha, msg, client)
            await _update_ref(tok, owner, repo, branch, head_sha, client)
            commits += 1

            if on_batch_done:
                await on_batch_done(batch_idx + 1, total_batches, head_sha)

    return {"commits": commits, "total_files": total_files, "head_sha": head_sha}
