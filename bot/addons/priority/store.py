def is_enabled() -> bool:
    return bool(addon_state.get(ADDON, "enabled", False))


def set_enabled(value: bool) -> None:
    addon_state.set_(ADDON, "enabled", bool(value))


def get_mode() -> str:
    mode = addon_state.get(ADDON, "mode", _DEFAULT_MODE)
    return mode if mode in MODES else _DEFAULT_MODE


def set_mode(mode: str) -> None:
    if mode in MODES:
        addon_state.set_(ADDON, "mode", mode)


def priority_directive() -> str:
    """System-prompt fragment honouring the setting. Empty when disabled."""
    if not is_enabled():
        return ""
    mode = get_mode()
    if mode == "only_bot":
        return (
            "## Приоритет ответа\n"
            "Пользователь включил режим «только возможности бота». Решай "
            "задачи ИСКЛЮЧИТЕЛЬНО встроенными функциями бота и знаниями "
            "модели. НЕ ходи в интернет и не предлагай внешний веб-поиск. "
            "Если для задачи нет встроенной возможности — честно скажи об "
            "этом и предложи ближайшую функцию бота."
        )
    if mode == "instruction":
        return (
            "## Приоритет ответа (инструкция)\n"
            "Действуй строго по дереву возможностей бота: сначала пойми "
            "класс задачи (например «генерация фото/видео»), затем спустись "
            "по веткам до конкретной функции (img2img → источники промптов "
            "и т.д.). Сначала используй встроенные возможности бота; в "
            "интернет — только если внутри бота решения нет.\n\n"
            + CAPABILITY_TREE
        )
    # bot_then_internet (default-on)
    return (
        "## Приоритет ответа\n"
        "Сначала пытайся решить задачу встроенными возможностями бота. "
        "Только если их недостаточно — используй интернет/веб-поиск как "
        "запасной вариант."
    )
