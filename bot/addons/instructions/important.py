def _overrides() -> dict:
    v = addon_state.get(ADDON, "status", None)
    return dict(v) if isinstance(v, dict) else {}


def _extra() -> list[dict]:
    """Notes added at runtime (e.g. by Hermes proposals). Optional."""
    v = addon_state.get(ADDON, "extra", None)
    return list(v) if isinstance(v, list) else []


def get_notes(source: str | None = None) -> list[dict]:
    ov = _overrides()
    out = []
    seeded = ([{**n, "source": "author"} for n in SEED]
              + [{**n, "source": "ai"} for n in AI_SEED]
              + [{**n, "source": n.get("source", "ai")} for n in _extra()])
    for n in seeded:
        m = dict(n)
        m["status"] = ov.get(n["id"], n.get("status", "idea"))
        m["status_label"] = _STATUS_LABEL.get(m["status"], m["status"])
        out.append(m)
    if source in ("author", "ai"):
        out = [n for n in out if n.get("source") == source]
    return out


def get_note(nid: str) -> dict | None:
    for n in get_notes():
        if n["id"] == nid:
            return n
    return None


def toggle_status(nid: str) -> str:
    cur = (get_note(nid) or {}).get("status", "idea")
    new = "works" if cur != "works" else "idea"
    ov = _overrides()
    ov[nid] = new
    addon_state.set_(ADDON, "status", ov)
    return new


def add_note(title: str, text: str, status: str = "idea") -> None:
    """Append a runtime note (for future Hermes proposals)."""
    import time
    extra = _extra()
    extra.append({
        "id": f"x{int(time.time())}",
        "title": (title or "").strip()[:120],
        "text": (text or "").strip()[:2000],
        "status": status if status in _STATUS_LABEL else "idea",
    })
    addon_state.set_(ADDON, "extra", extra)


def directive() -> str:
    """Compact text of the «❗Важно» notes — for Hermes / prompt consultation."""
    lines = ["## ВАЖНЫЕ ВЫВОДЫ ВЛАДЕЛЬЦА (учитывай при связке механизмов)"]
    for n in get_notes():
        lines.append(f"- [{n['status_label']}] {n['title']}: {n['text']}")
    return "\n".join(lines)
